    /// <summary>White text with a dark outline at (x, y) = top-left, each font pixel <paramref name="scale"/>² image pixels.</summary>
    public static void Draw(byte[] rgb, int w, int h, string text, int x, int y, int scale)
    {
        foreach (var (dx, dy, white) in new[] { (1, 1, false), (0, 0, true) })
        {
            int cx = x + dx * scale;
            foreach (char ch in text)
            {
                if (Glyphs.TryGetValue(char.ToUpperInvariant(ch), out var g))
                    for (int r = 0; r < 7; r++)
                    for (int c = 0; c < 5; c++)
                        if (g[r][c] == '#') Fill(rgb, w, h, cx + c * scale, y + dy * scale + r * scale, scale, white);
                cx += 6 * scale;
            }
        }
    }

    private static void Fill(byte[] rgb, int w, int h, int x0, int y0, int s, bool white)
    {
        for (int y = y0; y < y0 + s; y++)
        for (int x = x0; x < x0 + s; x++)
        {
            if (x < 0 || y < 0 || x >= w || y >= h) continue;
            int k = (y * w + x) * 3;
            byte v = white ? (byte)250 : (byte)20;
            rgb[k] = v; rgb[k + 1] = v; rgb[k + 2] = v;
        }
    }
