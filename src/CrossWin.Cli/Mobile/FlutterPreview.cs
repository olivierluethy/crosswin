using System.Diagnostics;
using System.Net;
using System.Net.Sockets;
using System.Reflection;
using System.Text;
using System.Text.Json;

namespace CrossWin.Mobile;

/// <summary>
/// Runs a Flutter app from source in the browser, inside device frames of real phone sizes, without Xcode,
/// Android Studio or an emulator. The app is compiled to the web by the Flutter SDK; a generated entry point
/// (in the work copy only) gives it each device's platform behaviour (iOS: Cupertino scrolling, transitions and
/// gestures; Android: Material) and safe-area insets. Every saved change is mirrored and the frames reload.
///
/// What it is not: real iOS or Android. Platform plugins (photo library, contacts, notifications …) have no web
/// implementation and report errors; system fonts are the browser's.
/// </summary>
public sealed class FlutterPreview
{
    private readonly HostEnv _env;
    private readonly MobileProject _p;
    private readonly string _work, _src;
    private Process? _flutter;
    private string? _appUrl;
    private int _version;
    private string _status = "starting";
    private string? _error;
    private readonly object _gate = new();
    private DateTime _lastChange;
    private Timer? _debounce;

    public FlutterPreview(HostEnv env, MobileProject p)
    {
        if (p.Kind != MobileKind.Flutter) throw new CrossWinException($"preview runs Flutter apps; {p.Name} is {p.KindLabel}.");
        _env = env;
        _p = p;
        _work = AndroidBuild.WorkDir(env, p);
        _src = Path.Combine(_work, "src");
    }

    // ------------------------------------------------------------------ work copy

    /// <summary>Generated in the work copy only: web/ (when the project has none) and the preview entry point.</summary>
    private IReadOnlySet<string> Generated =>
        Directory.Exists(Path.Combine(_p.Root, "web")) ? new HashSet<string>() : new HashSet<string> { "web" };

    private void Sync() => Commands.Mirror(_p.Root, _src, MobileProject.MirrorSkip, Generated);

    private void Prepare(string flutter)
    {
        Console.WriteLine($"Mirroring {_p.Root} -> {_src}");
        Sync();
        if (!File.Exists(Path.Combine(_src, "web", "index.html")))
        {
            Console.WriteLine("Adding a web target to the work copy (your project is not changed) ...");
            var r = Proc.Run(flutter, new[] { "create", ".", "--platforms", "web", "--project-name", _p.Name }, null, _src);
            if (r.ExitCode != 0) throw new CrossWinException("flutter create --platforms web failed:\n" + r.Output.Trim());
        }
        string entry = Path.Combine(_src, ".crosswin", "preview_main.dart");
        Directory.CreateDirectory(Path.GetDirectoryName(entry)!);
        File.WriteAllText(entry, EntryPoint(_p.Name));
    }

    /// <summary>
    /// Platform override and safe-area insets come from the frame's URL (cw_os, cw_top, cw_bottom); then the app's
    /// own main() runs unchanged. A custom binding wraps the root in a MediaQuery with the device's insets, which
    /// MaterialApp/CupertinoApp pick up as their ambient MediaQuery.
    /// </summary>
    public static string EntryPoint(string package) => $$"""
        // Generated by CrossWin for the device preview. Not part of your project.
        import 'package:flutter/foundation.dart';
        import 'package:flutter/widgets.dart';
        import 'package:{{package}}/main.dart' as app;

        void main() {
          final q = Uri.base.queryParameters;
          debugDefaultTargetPlatformOverride =
              q['cw_os'] == 'android' ? TargetPlatform.android : TargetPlatform.iOS;
          final insets = EdgeInsets.only(
            top: double.tryParse(q['cw_top'] ?? '') ?? 0,
            bottom: double.tryParse(q['cw_bottom'] ?? '') ?? 0,
          );
          _CrossWinBinding(insets);
          debugPrint('crosswin: ${q['cw_device']} with ${debugDefaultTargetPlatformOverride!.name} behaviour, insets $insets');
          app.main();
        }

        class _CrossWinBinding extends WidgetsFlutterBinding {
          _CrossWinBinding(this.insets);
          final EdgeInsets insets;

          @override
          Widget wrapWithDefaultView(Widget rootWidget) {
            final view = platformDispatcher.implicitView!;
            return View(
              view: view,
              child: Builder(
                builder: (context) {
                  final mq = MediaQueryData.fromView(view);
                  return MediaQuery(
                    data: mq.copyWith(padding: insets, viewPadding: insets),
                    child: rootWidget,
                  );
                },
              ),
            );
          }
        }
        """;

    // ------------------------------------------------------------------ flutter

    private void StartFlutter(string flutter)
    {
        int port = FreePort();
        var psi = Proc.Start(flutter, new[] { "run", "-d", "web-server", "--web-hostname", "127.0.0.1", "--web-port", port.ToString(),
            "-t", ".crosswin/preview_main.dart" }, null, _src);
        psi.RedirectStandardInput = true;
        _flutter = Process.Start(psi)!;
        string log = Path.Combine(_work, "preview.log");
        var w = new StreamWriter(log) { AutoFlush = true };
        void OnLine(string? l)
        {
            if (l == null) return;
            lock (_gate) w.WriteLine(l);
            string t = l.Trim();
            if (t.Contains("is being served at"))
            {
                _appUrl = $"http://127.0.0.1:{port}/";
                SetStatus("running");
            }
            else if (t.StartsWith("Restarted application") || t.StartsWith("Reloaded") || t.Contains("Recompile complete"))
            {
                Interlocked.Increment(ref _version);
                SetStatus("running");
                Console.WriteLine($"  reloaded ({DateTime.Now:HH:mm:ss})");
            }
            else if (t.Contains("Error:") || t.Contains("error:") || t.StartsWith("Target dart2js failed") || t.Contains("Compiler message:"))
            {
                _error = t;
                Console.WriteLine("  " + t);
            }
            else if (t.StartsWith("Waiting for connection") || t.StartsWith("Launching") || t.StartsWith("Compiling")) Console.WriteLine("  " + t);
        }
        _flutter.OutputDataReceived += (_, e) => OnLine(e.Data);
        _flutter.ErrorDataReceived += (_, e) => OnLine(e.Data);
        _flutter.BeginOutputReadLine();
        _flutter.BeginErrorReadLine();
        Console.WriteLine($"Compiling {_p.Name} for the preview (first time ~30–60 s) ... log: {log}");
    }

    private void SetStatus(string s) { _status = s; if (s == "running") _error = null; }

    /// <summary>Mirror the change, then ask Flutter for a hot restart; the frames reload when it is compiled.</summary>
    public void Reload()
    {
        try { Sync(); }
        catch (IOException) { return; } // an editor is mid-save; the watcher fires again
        SetStatus("reloading");
        _flutter?.StandardInput.WriteLine("R");
        _flutter?.StandardInput.Flush();
        // Browsers without the debugger connection only get "Recompile complete"; bump anyway if nothing comes.
        int before = _version;
        _ = Task.Delay(6000).ContinueWith(_ => { if (_version == before) { Interlocked.Increment(ref _version); SetStatus("running"); } });
    }

    private void Watch()
    {
        var fsw = new FileSystemWatcher(_p.Root) { IncludeSubdirectories = true, EnableRaisingEvents = true };
        void Changed(string path)
        {
            string rel = Path.GetRelativePath(_p.Root, path);
            if (rel.Split(Path.DirectorySeparatorChar).Any(MobileProject.MirrorSkip.Contains)) return;
            _lastChange = DateTime.UtcNow;
            _debounce?.Dispose();
            _debounce = new Timer(_ => { Console.WriteLine($"  change: {rel}"); Reload(); }, null, 400, Timeout.Infinite);
        }
        fsw.Changed += (_, e) => Changed(e.FullPath);
        fsw.Created += (_, e) => Changed(e.FullPath);
        fsw.Deleted += (_, e) => Changed(e.FullPath);
        fsw.Renamed += (_, e) => Changed(e.FullPath);
        GC.KeepAlive(fsw);
        _watcher = fsw;
    }
    private FileSystemWatcher? _watcher;

    // ------------------------------------------------------------------ preview page

    public int Run(int? port, bool openBrowser, string devices)
    {
        string flutter = HostEnv.FindOnPath("flutter")
            ?? throw new CrossWinException("Flutter SDK not found on PATH. Install it (https://docs.flutter.dev/get-started/install) — no Xcode or Android Studio needed for the preview.");
        Prepare(flutter);
        StartFlutter(flutter);
        Watch();

        int p = port ?? FreePort();
        var http = new HttpListener();
        http.Prefixes.Add($"http://127.0.0.1:{p}/");
        http.Start();
        string url = $"http://127.0.0.1:{p}/crosswin/?devices={devices}";
        Console.WriteLine($"""

            Device preview: {url}
              Watching {_p.Root} — save a file and every frame reloads.
              Ctrl+C stops the preview.

            """);
        if (openBrowser) OpenBrowser(url);

        Console.CancelKeyPress += (_, e) => { e.Cancel = true; http.Stop(); };
        try
        {
            while (http.IsListening)
            {
                HttpListenerContext ctx;
                try { ctx = http.GetContext(); } catch (HttpListenerException) { break; } catch (ObjectDisposedException) { break; }
                ThreadPool.QueueUserWorkItem(_ => Serve(ctx));
            }
        }
        finally
        {
            try { _flutter?.StandardInput.WriteLine("q"); if (_flutter?.WaitForExit(3000) == false) _flutter.Kill(true); } catch { }
            Console.WriteLine("Preview stopped.");
        }
        return 0;
    }

    private static readonly HttpClient Upstream = new(new SocketsHttpHandler { MaxConnectionsPerServer = 64 }) { Timeout = TimeSpan.FromMinutes(2) };

    /// <summary>
    /// The bench lives under /crosswin/; every other path is the Flutter app, proxied from Flutter's web server.
    /// One origin lets the bench see when a frame has started, so frames can load one after another.
    /// </summary>
    private void Serve(HttpListenerContext ctx)
    {
        try
        {
            string path = ctx.Request.Url!.AbsolutePath;
            if (path == "/crosswin/api/state") Json(ctx, State());
            else if (path == "/crosswin/api/reload" && ctx.Request.HttpMethod == "POST") { Reload(); Json(ctx, new { ok = true }); }
            else if (path is "/crosswin" or "/crosswin/")
            {
                using var s = Assembly.GetExecutingAssembly().GetManifestResourceStream("preview.html")!;
                ctx.Response.ContentType = "text/html; charset=utf-8";
                ctx.Response.Headers["Cache-Control"] = "no-store";
                s.CopyTo(ctx.Response.OutputStream);
            }
            else if (_appUrl is { } app) Proxy(ctx, app);
            else ctx.Response.StatusCode = 503;
        }
        catch { try { ctx.Response.StatusCode = 502; } catch { } }
        finally { try { ctx.Response.Close(); } catch { } }
    }

    private static void Proxy(HttpListenerContext ctx, string app)
    {
        var req = new HttpRequestMessage(new HttpMethod(ctx.Request.HttpMethod), app.TrimEnd('/') + ctx.Request.Url!.PathAndQuery);
        using var resp = Upstream.Send(req, HttpCompletionOption.ResponseHeadersRead);
        ctx.Response.StatusCode = (int)resp.StatusCode;
        if (resp.Content.Headers.ContentType is { } ct) ctx.Response.ContentType = ct.ToString();
        foreach (var h in new[] { "Cache-Control", "ETag", "Last-Modified" })
            if (resp.Headers.TryGetValues(h, out var v) || resp.Content.Headers.TryGetValues(h, out v)) ctx.Response.Headers[h] = string.Join(",", v);
        using var body = resp.Content.ReadAsStream();
        body.CopyTo(ctx.Response.OutputStream);
    }

    private object State() => new
    {
        project = _p.Name,
        root = _p.Root,
        status = _appUrl == null ? (_flutter?.HasExited == true ? "stopped" : "compiling") : _status,
        error = _flutter?.HasExited == true ? "Flutter stopped — see preview.log in " + _work : _error,
        appUrl = _appUrl == null ? null : "/",
        version = _version,
        devices = DeviceCatalog.All.Select(d => new
        {
            id = d.Id, name = d.Name, os = d.Os == MobileOs.Ios ? "ios" : "android",
            width = d.LogicalWidth, height = d.LogicalHeight, top = d.TopInset, bottom = d.BottomInset,
            size = d.LogicalSize, ratio = d.PixelRatio,
        }),
    };

    private static void Json(HttpListenerContext ctx, object o)
    {
        byte[] b = JsonSerializer.SerializeToUtf8Bytes(o);
        ctx.Response.ContentType = "application/json";
        ctx.Response.Headers["Cache-Control"] = "no-store";
        ctx.Response.OutputStream.Write(b);
    }

    public static int FreePort()
    {
        var l = new TcpListener(IPAddress.Loopback, 0);
        l.Start();
        int port = ((IPEndPoint)l.LocalEndpoint).Port;
        l.Stop();
        return port;
    }

    public static void OpenBrowser(string url)
    {
        try
        {
            if (OperatingSystem.IsWindows()) Process.Start(new ProcessStartInfo(url) { UseShellExecute = true });
            else Process.Start(OperatingSystem.IsMacOS() ? "open" : "xdg-open", url);
        }
        catch { Console.WriteLine("Open the URL above in your browser."); }
    }
}
